import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import express from "express";
import sharp from "sharp";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { Store } from "./store.js";
import { buildMcpServer } from "./mcp.js";
import { addBlock, updateBlock, blockPath, logBlock, posterBlock, wrapBlock, describeBlock, webBlockRoutes } from "./web-blocks.js";
import { renderPage, claudeLayerSvg } from "./render.js";
import { itemBBox, prepareBatch } from "./items.js";

const directory = fs.mkdtempSync(path.join(os.tmpdir(), "claudebook-web-"));
const store = new Store(directory), page = store.listNotebooks()[0].pages[0];
const server = buildMcpServer(store), client = new Client({ name: "web-blocks-selftest", version: "1" });
const [a,b] = InMemoryTransport.createLinkedPair();
await server.connect(b); await client.connect(a);
const app = express(); app.use(express.json({ limit: "4mb" })); const routes = express.Router(); webBlockRoutes(routes, store); app.use(routes);
const http = app.listen(0, "127.0.0.1"); await new Promise<void>(r => http.once("listening", r));
const address = http.address(); assert.ok(address && typeof address !== "string");
const base = `http://127.0.0.1:${address.port}`;
try {
  const events: unknown[] = []; store.on(e => events.push(e));
  const call = async (name: string, args: Record<string, unknown>, error = false) => {
    const result = await client.callTool({ name, arguments: args }); assert.equal(!!result.isError, error, JSON.stringify(result.content));
    assert.ok((result.content as { type: string }[]).filter(c => c.type === "image").length <= 1);
    return (result.content as { text: string }[])[0].text;
  };
  const added = JSON.parse(await call("add_web_block", { x: 100, y: 200, w: 700, h: 400, title: "Fragment", html: "<button>Try it</button>" }));
  let item = page.claudeLayer.find(i => i.id === added.id)!; assert.equal(item.type, "web");
  if (item.type !== "web") throw new Error("Expected web item");
  assert.deepEqual(added.bbox, { x: 100, y: 200, w: 700, h: 400 });
  assert.equal(item.autoplay, true);
  const fragment = fs.readFileSync(blockPath(store, item.file), "utf8");
  assert.match(fragment, /viewport/); assert.match(fragment, /Content-Security-Policy/); assert.match(fragment, /height:100%/);
  assert.equal(fragment.match(/data-claudebook-bridge/g)?.length, 1);
  assert.ok(fragment.indexOf("Content-Security-Policy") < fragment.indexOf("<button>"));
  const full = addBlock(store, page.id, { x: 0,y: 0,w: 300,h: 200,title: "Full",html: "<!doctype html><html><head><title>Document</title></head><body>Full document</body></html>" });
  assert.equal(full.type, "web"); if (full.type !== "web") throw new Error("Expected web item");
  const fullHTML = fs.readFileSync(blockPath(store, full.file), "utf8"); assert.match(fullHTML, /Full document/); assert.equal(fullHTML.match(/data-claudebook-bridge/g)?.length, 1);
  assert.throws(() => wrapBlock("x".repeat(2*1024*1024)), /at most 1 MB/);
  await call("add_web_block", { x: 0,y: 0,w: 200,h: 100,title: "Too large",html: "x".repeat(2*1024*1024) }, true);
  const before = await renderPage(store, page); assert.ok(before.length > 1000);
  assert.match(claudeLayerSvg(page, store), /Interactive block, open it on the iPad/);
  const png = await sharp({ create: { width: 70,height: 40,channels: 4,background: "#ff0000" } }).png().toBuffer();
  const poster = await fetch(`${base}/pages/${page.id}/blocks/${item.id}/poster`, { method: "PUT",headers: { "Content-Type": "application/json" },body: JSON.stringify({ rev: 1,png: png.toString("base64") }) }); assert.equal(poster.status, 200);
  const after = await renderPage(store, page); assert.notDeepEqual(before, after);
  const pixel = await sharp(after).extract({ left: 400,top: 400,width: 1,height: 1 }).raw().toBuffer(); assert.equal(pixel[0], 255); assert.equal(pixel[1], 0);
  const posted = await fetch(`${base}/pages/${page.id}/blocks/${item.id}/log`, { method: "POST",headers: { "Content-Type": "application/json" },body: JSON.stringify({ rev: 1,lines: ["ReferenceError: g is not defined (line 14)"] }) }); assert.equal(posted.status, 200);
  assert.match(await call("get_current_page", {}), /ReferenceError: g is not defined/);
  const asset = await fetch(`${base}/blocks/${item.file}`); assert.equal(asset.status, 200); assert.match(asset.headers.get("content-security-policy")!, /sandbox allow-scripts/);
  assert.equal((await fetch(`${base}/blocks/not-a-file`)).status, 404);
  assert.equal((await fetch(`${base}/blocks/${item.file.replace("html", "txt")}`)).status, 404);
  const firstFile = item.file;
  const fixed = JSON.parse(await call("update_web_block", { id: item.id,html: "<canvas>Fixed</canvas>",title: "Fixed",w: 650 }));
  assert.equal(fixed.id, item.id); assert.equal(fixed.rev, 2);
  item = page.claudeLayer.find(i => i.id === added.id)!; if (item.type !== "web") throw new Error("Expected web item");
  assert.equal(item.x, 100); assert.equal(item.y, 200); assert.equal(item.w, 650); assert.equal(item.poster, undefined); assert.deepEqual(item.logs, []);
  assert.ok(!fs.existsSync(blockPath(store, firstFile)));
  assert.doesNotMatch(await call("get_current_page", {}), /ReferenceError: g/);
  assert.throws(() => logBlock(store, page.id, item.id, 1, ["stale"]), /Stale/);
  await assert.rejects(() => posterBlock(store,page.id,item.id,1,png), /Stale/);
  await assert.rejects(() => posterBlock(store,page.id,item.id,2,Buffer.from("not a PNG")));
  logBlock(store,page.id,item.id,2,Array.from({length:30},(_,i)=>"line " + i));
  assert.match(describeBlock(page.claudeLayer.find(i=>i.id===item.id)!), /line 29/);
  assert.equal(page.claudeLayer.find(i=>i.id===item.id)?.logs?.length,20);
  assert.match(prepareBatch([{type:"web"}]).warnings[0].warning,/use add_web_block/);
  const moved = store.moveClaudeItems(page.id,[item.id],10,20)[0]; assert.deepEqual(itemBBox(moved),{x:110,y:220,w:650,h:400});
  const copied = store.copyClaudeItems(page.id,[item.id],30,40)[0]; assert.notEqual(copied.id,item.id); assert.deepEqual(itemBBox(copied),{x:140,y:260,w:650,h:400});
  assert.equal(copied.type,"web"); if(copied.type!=="web") throw new Error("Expected web item");
  assert.equal(copied.file,item.file);
  const oldCopyFile = copied.file;
  store.removeClaudeItemsByIds(page.id,[item.id]); assert.ok(fs.existsSync(blockPath(store,oldCopyFile)));
  store.removeClaudeItemsByIds(page.id,[copied.id]); assert.ok(!fs.existsSync(blockPath(store,oldCopyFile)));
  const assetCount = fs.readdirSync(path.join(directory,"blocks")).length;
  const same = addBlock(store,page.id,{x:0,y:0,w:300,h:200,title:"Same",html:"<!doctype html><html><head><title>Document</title></head><body>Full document</body></html>"});
  assert.equal(fs.readdirSync(path.join(directory,"blocks")).length,assetCount);
  assert.ok(events.length>=10);
  assert.throws(()=>updateBlock(store,page.id,{id:same.id,w:-10}),/>0/);
  console.log("[web blocks] MCP fragment/full document, size limit, bridge/policy, rev/logs/poster routes, render pixels, move/copy/erase, dedupe/sweep and broadcasts passed");
} finally {
  await client.close(); await server.close(); await new Promise<void>((resolve,reject)=>http.close(e=>e?reject(e):resolve())); fs.rmSync(directory,{recursive:true,force:true});
}
